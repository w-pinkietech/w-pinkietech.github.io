// Generate self-hosted, character-subset web fonts for the site.
//
// Why: the previous setup pulled Inter + Noto Sans JP through a chained
// `@import` to fonts.googleapis.com inside the bundled CSS. That is the slowest
// possible way to load fonts — the browser cannot discover it until the CSS is
// parsed, then it opens two fresh third-party connections (googleapis, then
// gstatic) in series before a single glyph arrives, and Noto Sans JP is a heavy
// Japanese family. Because every rendered character on this site is known at
// build time, we can ask Google Fonts for a `text=`-scoped subset of exactly the
// glyphs we use, download the resulting woff2, and self-host it. Same-origin,
// preloadable, and a fraction of the bytes.
//
// This script hits the network and Google's kit URLs are not deterministic, so
// it is intentionally NOT part of `npm run build`. Run it manually when the
// site copy changes:  `npm run fonts:build`  then commit the regenerated files.

import { mkdir, writeFile } from 'node:fs/promises'

import { charsetSignature, collectCharset } from './lib/charset.mjs'

const rootUrl = new URL('../', import.meta.url)
const fontsDir = new URL('public/brand/fonts/', rootUrl)
const generatedCssPath = new URL('src/fonts.generated.css', rootUrl)

// Modern Chrome UA so Google Fonts serves woff2 (older UAs get ttf/woff).
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'

const families = [
  { name: 'Inter', slug: 'inter' },
  { name: 'Noto Sans JP', slug: 'noto-sans-jp' },
]
const weights = [400, 500, 600]

async function fetchSubsetCss(family, weight, charset) {
  const url =
    'https://fonts.googleapis.com/css2' +
    `?family=${encodeURIComponent(family)}:wght@${weight}` +
    `&text=${encodeURIComponent(charset.join(''))}` +
    '&display=swap'
  const res = await fetch(url, { headers: { 'User-Agent': UA } })
  if (!res.ok) throw new Error(`Google Fonts CSS ${res.status} for ${family} ${weight}`)
  return res.text()
}

function extractWoff2Url(css) {
  const match = css.match(/src:\s*url\((https:\/\/[^)]+)\)\s*format\('woff2'\)/)
  if (!match) throw new Error('Could not find a woff2 URL in the Google Fonts CSS')
  return match[1]
}

async function downloadFont(url, destPath) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } })
  if (!res.ok) throw new Error(`Font download ${res.status} for ${url}`)
  const buffer = Buffer.from(await res.arrayBuffer())
  await writeFile(destPath, buffer)
  return buffer.length
}

async function main() {
  const charset = await collectCharset(rootUrl)
  const signature = charsetSignature(charset)
  const nonAscii = charset.filter((c) => c.codePointAt(0) > 0x7f).length
  console.log(`Collected ${charset.length} unique characters (${nonAscii} non-ASCII).`)

  await mkdir(fontsDir, { recursive: true })

  const faces = []
  for (const family of families) {
    for (const weight of weights) {
      const css = await fetchSubsetCss(family.name, weight, charset)
      const woff2Url = extractWoff2Url(css)
      const fileName = `${family.slug}-${weight}.woff2`
      const bytes = await downloadFont(woff2Url, new URL(fileName, fontsDir))
      console.log(`  ${family.name} ${weight}: ${(bytes / 1024).toFixed(1)} KB -> ${fileName}`)
      faces.push(
        [
          '@font-face {',
          `  font-family: '${family.name}';`,
          '  font-style: normal;',
          `  font-weight: ${weight};`,
          '  font-display: swap;',
          `  src: url('/brand/fonts/${fileName}') format('woff2');`,
          '}',
        ].join('\n'),
      )
    }
  }

  const header =
    '/* Generated by scripts/subset-fonts.mjs. Do not edit by hand. */\n' +
    '/* Regenerate with `npm run fonts:build` after changing site copy. */\n' +
    // Fingerprint of the glyph set these fonts were built for. check-design.mjs
    // recomputes it from source and fails CI if the copy drifted without a
    // regeneration. Keep this line — it is the drift-detection contract.
    `/* charset-sha256: ${signature} */\n`
  await writeFile(generatedCssPath, `${header}\n${faces.join('\n\n')}\n`, 'utf8')
  console.log(`Wrote ${faces.length} @font-face rules to src/fonts.generated.css`)
}

await main()
